-- Existing accounts have no legal-entity model. Start with explicit single-member
-- organizations, retaining account UUIDs as the migration bridge (not KYB status).
CREATE TABLE organizations (
    id UUID PRIMARY KEY, name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_calculated_at TIMESTAMP WITH TIME ZONE,
    last_manual_at TIMESTAMP WITH TIME ZONE,
    config_version BIGINT NOT NULL DEFAULT 0, dirty BOOLEAN NOT NULL DEFAULT TRUE,
    retry_after TIMESTAMP WITH TIME ZONE, failures INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE organization_members (
    user_id UUID PRIMARY KEY REFERENCES users(id),
    organization_id UUID NOT NULL REFERENCES organizations(id)
);
CREATE INDEX idx_org_members_org ON organization_members(organization_id);
CREATE INDEX idx_org_trust_work ON organizations(dirty, retry_after, last_calculated_at);
INSERT INTO organizations(id,name,created_at)
    SELECT id,name,created_at FROM users WHERE role IN ('BUYER','SELLER');
INSERT INTO organization_members(user_id,organization_id) SELECT id,id FROM organizations;

CREATE TABLE trust_scoring_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rules JSONB NOT NULL, actor_id UUID REFERENCES users(id),
    reason VARCHAR(1000) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE trust_events (
    id UUID PRIMARY KEY, organization_id UUID NOT NULL REFERENCES organizations(id),
    user_id UUID REFERENCES users(id), deal_id UUID REFERENCES deals(id),
    milestone_id UUID REFERENCES milestones(id), counterparty_id UUID REFERENCES organizations(id),
    role VARCHAR(255) NOT NULL CHECK (role IN ('OVERALL','BUYER','VENDOR')),
    event_type VARCHAR(255) NOT NULL, event_value NUMERIC(19,4), currency VARCHAR(255),
    severity INTEGER NOT NULL CHECK (severity BETWEEN 1 AND 5),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL, metadata JSONB NOT NULL,
    source VARCHAR(255) NOT NULL, source_key VARCHAR(300) NOT NULL UNIQUE,
    processed BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_trust_events_org_time ON trust_events(organization_id,occurred_at,id);
CREATE INDEX idx_trust_events_type_time ON trust_events(event_type,occurred_at);
CREATE INDEX idx_trust_events_pending ON trust_events(organization_id,processed,created_at);
CREATE INDEX idx_trust_events_deal ON trust_events(deal_id);
CREATE INDEX idx_trust_events_milestone ON trust_events(milestone_id);
CREATE INDEX idx_trust_events_counterparty ON trust_events(counterparty_id);

CREATE TABLE trust_scores (
    id UUID PRIMARY KEY, organization_id UUID NOT NULL REFERENCES organizations(id),
    role VARCHAR(255) NOT NULL CHECK (role IN ('OVERALL','BUYER','VENDOR')),
    overall_score DOUBLE PRECISION NOT NULL CHECK (overall_score BETWEEN 0 AND 100),
    confidence_score DOUBLE PRECISION NOT NULL CHECK (confidence_score BETWEEN 0 AND 100),
    trust_level VARCHAR(255) NOT NULL, config_version BIGINT NOT NULL,
    algorithm_version VARCHAR(255) NOT NULL, data_points BIGINT NOT NULL,
    last_calculated_at TIMESTAMP WITH TIME ZONE NOT NULL, result JSONB NOT NULL,
    UNIQUE (organization_id,role)
);
CREATE INDEX idx_trust_score_level ON trust_scores(trust_level,organization_id);
CREATE TABLE trust_score_history (
    id UUID PRIMARY KEY, organization_id UUID NOT NULL REFERENCES organizations(id),
    role VARCHAR(255) NOT NULL, previous_score DOUBLE PRECISION, new_score DOUBLE PRECISION NOT NULL,
    previous_level VARCHAR(255), new_level VARCHAR(255) NOT NULL,
    reason VARCHAR(1000) NOT NULL, trigger_event_id UUID REFERENCES trust_events(id),
    actor_id UUID REFERENCES users(id), config_version BIGINT NOT NULL,
    calculated_at TIMESTAMP WITH TIME ZONE NOT NULL, snapshot JSONB NOT NULL
);
CREATE INDEX idx_trust_history_org_role_time ON trust_score_history(organization_id,role,calculated_at);
CREATE INDEX idx_trust_history_event ON trust_score_history(trigger_event_id);
CREATE TABLE trust_signal (
    id UUID PRIMARY KEY, organization_id UUID NOT NULL REFERENCES organizations(id),
    calculation_id UUID NOT NULL REFERENCES trust_score_history(id), role VARCHAR(255) NOT NULL,
    signal_type VARCHAR(255) NOT NULL, category VARCHAR(255) NOT NULL,
    impact DOUBLE PRECISION NOT NULL, severity INTEGER NOT NULL,
    description VARCHAR(1000) NOT NULL, source_event_id UUID REFERENCES trust_events(id),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL, expires_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_trust_signal_calculation ON trust_signal(organization_id,calculation_id,role);
CREATE INDEX idx_trust_signal_event ON trust_signal(source_event_id);
CREATE TABLE trust_manual_review (
    id UUID PRIMARY KEY, organization_id UUID NOT NULL REFERENCES organizations(id),
    admin_id UUID NOT NULL REFERENCES users(id), reason VARCHAR(1000) NOT NULL,
    status VARCHAR(255) NOT NULL CHECK (status IN ('OPEN','RESOLVED')),
    resolved_by UUID REFERENCES users(id), resolution VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, resolved_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_trust_review_queue ON trust_manual_review(status,created_at);
CREATE INDEX idx_trust_review_org ON trust_manual_review(organization_id);

CREATE TABLE trust_audit_receipts (
    audit_id UUID PRIMARY KEY REFERENCES audit_logs(id), captured_at TIMESTAMP WITH TIME ZONE NOT NULL
);
